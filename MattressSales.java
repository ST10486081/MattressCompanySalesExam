public class PrintProduct {
    private Product product;
    private static final String REPORT_FILENAME = "report.txt";

    public PrintProduct(Product product) {
        this.product = product;
    }

    public void printTotalProductSales() {
        int total = product.getTotalProductsSold();
        String message = "Total Products Sold: " + total;
       
        // Print to console
        System.out.println(message);
       
        // Save to separate report file
        writeReportLine(message);
    }

    public void printAverageProductSales() {
        double average = product.getAverageProductsSold();
        String message = "Average Products Sold: " + average;
       
        // Print to console
        System.out.println(message);
       
        // Save to separate report file
        writeReportLine(message);
    }

    public void printMostPopularProductSale() {
        String popularProduct = product.getMostPopularProduct();
        String message = "Most Popular Product: " + popularProduct;
       
        // Print to console
        System.out.println(message);
       
        // Save to separate report file
        writeReportLine(message);
    }

    /**
     * Helper method to append a report line to 'report.txt'
     */
    private void writeReportLine(String content) {
        try (PrintWriter writer = new PrintWriter(new FileWriter(REPORT_FILENAME, true))) {
            writer.println(content);
        } catch (IOException e) {
            System.err.println("Error writing to report file: " + e.getMessage());
        }
    }
   
    /**
     * Optional utility method to write the full combined report block at once.
     */
    public void generateFullReportFile() {
        try (PrintWriter writer = new PrintWriter(new FileWriter(REPORT_FILENAME, false))) {
            writer.println("=== PRODUCT SALES REPORT ===");
            writer.println("Total Products Sold: " + product.getTotalProductsSold());
            writer.println("Average Products Sold: " + product.getAverageProductsSold());
            writer.println("Most Popular Product: " + product.getMostPopularProduct());
            writer.println("============================");
            System.out.println("Full report successfully saved to " + REPORT_FILENAME);
        } catch (IOException e) {
            System.err.println("Error generating full report file: " + e.getMessage());
        }
    }
}


          
       
